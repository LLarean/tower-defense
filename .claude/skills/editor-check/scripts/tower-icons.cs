const int Size = 256;
var guids = UnityEditor.AssetDatabase.FindAssets("t:TowerAsset", new[] { "Assets/Game/Config/Towers" });
var scene = UnityEditor.SceneManagement.EditorSceneManager.NewScene(UnityEditor.SceneManagement.NewSceneSetup.EmptyScene, UnityEditor.SceneManagement.NewSceneMode.Additive);
UnityEngine.SceneManagement.SceneManager.SetActiveScene(scene);
var lightObject = new UnityEngine.GameObject("Key");
var light = lightObject.AddComponent<UnityEngine.Light>();
light.type = UnityEngine.LightType.Directional;
light.intensity = 1.6f;
lightObject.transform.rotation = UnityEngine.Quaternion.Euler(40f, -30f, 0f);
var fill = new UnityEngine.GameObject("Fill").AddComponent<UnityEngine.Light>();
fill.type = UnityEngine.LightType.Directional;
fill.intensity = 0.6f;
fill.transform.rotation = UnityEngine.Quaternion.Euler(20f, 150f, 0f);
var camera = new UnityEngine.GameObject("Camera").AddComponent<UnityEngine.Camera>();
camera.clearFlags = UnityEngine.CameraClearFlags.SolidColor;
camera.backgroundColor = new UnityEngine.Color(0f, 0f, 0f, 0f);
camera.fieldOfView = 25f;
UnityEngine.Rendering.Universal.CameraExtensions.GetUniversalAdditionalCameraData(camera).renderPostProcessing = false;
var target = new UnityEngine.RenderTexture(Size, Size, 24, UnityEngine.RenderTextureFormat.ARGB32) { antiAliasing = 8 };
camera.targetTexture = target;
var report = "";
foreach (var guid in guids)
{
    var path = UnityEditor.AssetDatabase.GUIDToAssetPath(guid);
    var asset = UnityEditor.AssetDatabase.LoadAssetAtPath<Game.Stage.Config.TowerAsset>(path);
    var model = (UnityEngine.GameObject)UnityEditor.PrefabUtility.InstantiatePrefab(asset.Model, scene);
    model.transform.position = UnityEngine.Vector3.zero;
    var bounds = new UnityEngine.Bounds(model.transform.position, UnityEngine.Vector3.zero);
    foreach (var renderer in model.GetComponentsInChildren<UnityEngine.Renderer>()) bounds.Encapsulate(renderer.bounds);
    var radius = bounds.extents.magnitude;
    var direction = UnityEngine.Quaternion.Euler(18f, 35f, 0f) * UnityEngine.Vector3.back;
    camera.transform.position = bounds.center - direction * (radius / UnityEngine.Mathf.Sin(camera.fieldOfView * 0.5f * UnityEngine.Mathf.Deg2Rad)) * 1.02f;
    camera.transform.LookAt(bounds.center);
    camera.Render();
    UnityEngine.RenderTexture.active = target;
    var image = new UnityEngine.Texture2D(Size, Size, UnityEngine.TextureFormat.RGBA32, false);
    image.ReadPixels(new UnityEngine.Rect(0, 0, Size, Size), 0, 0);
    image.Apply();
    UnityEngine.RenderTexture.active = null;
    var file = "Assets/Game/Art/Icons/" + asset.name + "Tower.png";
    System.IO.File.WriteAllBytes(file, image.EncodeToPNG());
    UnityEngine.Object.DestroyImmediate(image);
    UnityEngine.Object.DestroyImmediate(model);
    report += asset.name + " r=" + radius.ToString("0.0") + " ";
}
camera.targetTexture = null;
target.Release();
UnityEditor.SceneManagement.EditorSceneManager.CloseScene(scene, true);
UnityEditor.AssetDatabase.Refresh();
return report;
